#!/usr/bin/env python3
"""Isolated terminal input sink: never interprets/executes received text."""
import json
import os
import pathlib
import select
import sys
import termios
import tty

root=pathlib.Path(__file__).resolve().parents[1]
report=root/'artifacts/evidence/console-harness.json'
report.parent.mkdir(parents=True,exist_ok=True)
fd=sys.stdin.fileno(); previous=termios.tcgetattr(fd)
state=dict(inputBytes=0,submitCount=0,unexpectedControlCount=0)
report.write_text(json.dumps(state,indent=2)+'\n')
print('Veylume isolated input sink. Nothing is executed. Ctrl+C exits.\n',flush=True)
try:
    tty.setraw(fd)
    while True:
        if not select.select([fd],[],[],1)[0]:continue
        data=os.read(fd,65536)
        if not data or b'\x03' in data:break
        # Permit bracketed-paste wrappers generated by Terminal itself.
        data=data.replace(b'\x1b[200~',b'').replace(b'\x1b[201~',b'')
        state['inputBytes']+=len(data)
        state['submitCount']+=data.count(b'\r')+data.count(b'\n')
        state['unexpectedControlCount']+=sum(c<32 or c==127 for c in data)
        report.write_text(json.dumps(state,indent=2)+'\n')
        os.write(sys.stdout.fileno(), ('\rReceived bytes: %d  Submit: %d  Controls: %d    '%tuple(state.values())).encode())
finally:
    termios.tcsetattr(fd,termios.TCSADRAIN,previous)
    report.write_text(json.dumps(state,indent=2)+'\n')
    print('\nInput sink closed. No received text was logged.')
